  /// Получить название страны по ISO коду
  static String? getCountryName(String? isoCode) {
    if (isoCode == null || isoCode.isEmpty) return null;

    final normalizedCode = isoCode.toUpperCase();
    try {
      final country = _countries.firstWhere(
        (country) => country.isoCode == normalizedCode,
      );
      return country.name;
    } catch (e) {
      return null;
    }
  }

  /// Получить список всех стран
  static List<Country> get all => _countries;

  /// Получить объект страны по ISO коду
  static Country? getCountry(String? isoCode) {
    if (isoCode == null || isoCode.isEmpty) return null;

    final normalizedCode = isoCode.toUpperCase();
    try {
      return _countries.firstWhere(
        (country) => country.isoCode == normalizedCode,
      );
    } catch (e) {
      return null;
    }
  }
